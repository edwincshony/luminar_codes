"""
Write a program to merge two lists [1, 2, 3] and [4, 5, 6] and display the final list without modifying the original lists.

"""

lst1 = [1, 2, 3]

lst2 = [4, 5, 6]

merge_list = lst1 + lst2

print(f"Merged list is {merge_list}")

print(f"Original list1 is {lst1}")
print(f"Original list2 is {lst2}")